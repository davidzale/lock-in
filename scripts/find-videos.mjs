// Finds one embeddable technique video per exercise with the official YouTube Data API v3.
// Usage (your own API key, never committed):  YT_API_KEY=... node scripts/find-videos.mjs
// Keeps videos already chosen in src/lib/videos.ts and only fills the missing ones.
import { writeFileSync, readFileSync, existsSync } from 'node:fs'
import { EX, FAMILIES } from '../src/lib/program.ts'

const KEY = process.env.YT_API_KEY
if (!KEY) {
  console.error('Set YT_API_KEY first (Google Cloud → APIs & Services → YouTube Data API v3 → API key).')
  process.exit(1)
}

const src = readFileSync('src/lib/program.ts', 'utf8')
const used = new Set()
for (const f of Object.values(FAMILIES)) for (const l of f.levels) used.add(l.ex)
for (const m of src.matchAll(/\['([a-z0-9_]+)', \d+\]/g)) if (EX[m[1]]) used.add(m[1])
for (const m of src.matchAll(/FINISHER[^\n]+/g)) for (const x of m[0].matchAll(/'([a-z0-9_]+)'/g)) if (EX[x[1]]) used.add(x[1])

const TRUST = /physio|physical therap|therapy|\bpt\b|rehab|clinic|health|hospital|nhs|bupa|mayo|ace fitness|yoga|well\+good|howcast|livestrong|orthop|spine|posture|mobility/i
const STOP = new Set(['proper', 'form', 'exercise', 'beginner', 'bodyweight', 'how', 'to', 'the', 'pose', 'stretch', 'on'])
const iso = (d) => { const m = d.match(/PT(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?/) || []; return (+(m[1] || 0)) * 3600 + (+(m[2] || 0)) * 60 + (+(m[3] || 0)) }
const api = (path, params) => fetch(`https://www.googleapis.com/youtube/v3/${path}?${new URLSearchParams({ ...params, key: KEY })}`).then((r) => r.json())

const result = {}
if (existsSync('src/lib/videos.ts')) {
  const old = readFileSync('src/lib/videos.ts', 'utf8')
  for (const m of old.matchAll(/^ {2}([a-z0-9_]+): (\{.*\}),$/gm)) result[m[1]] = JSON.parse(m[2])
}

for (const id of [...used].sort()) {
  if (result[id]) continue
  const e = EX[id]
  const q = `${e.q || `${e.name.en} exercise`} how to`
  const words = (e.q || e.name.en).toLowerCase().split(/[^a-z0-9]+/).filter((w) => w && !STOP.has(w))
  const s = await api('search', { part: 'snippet', type: 'video', videoEmbeddable: 'true', maxResults: '10', q, relevanceLanguage: 'en', safeSearch: 'strict' })
  if (s.error) { console.error('API error:', s.error.message); break }
  const ids = (s.items || []).map((x) => x.id.videoId).join(',')
  if (!ids) { console.log(id.padEnd(18), 'NOT FOUND'); continue }
  const d = await api('videos', { part: 'contentDetails,statistics,snippet', id: ids })
  const scored = (d.items || [])
    .map((v) => ({ id: v.id, title: v.snippet.title, channel: v.snippet.channelTitle, sec: iso(v.contentDetails.duration), views: +(v.statistics.viewCount || 0) }))
    .filter((v) => v.sec >= 15 && v.sec <= 900)
    .map((v) => {
      const t = v.title.toLowerCase()
      const hit = words.filter((w) => t.includes(w)).length / Math.max(1, words.length)
      let sc = Math.log10(v.views + 10) + hit * 4
      if (TRUST.test(v.channel)) sc += 1.2
      if (/how to|tutorial|form|technique|guide|correct/i.test(v.title)) sc += 0.8
      if (v.sec > 480) sc -= 1.5
      return { ...v, sc, hit }
    })
    .filter((v) => v.hit >= 0.5)
    .sort((a, b) => b.sc - a.sc)
  const pick = scored[0]
  result[id] = pick ? { id: pick.id, title: pick.title, channel: pick.channel, sec: pick.sec } : null
  console.log(id.padEnd(18), pick ? `${pick.id}  ${pick.channel} — ${pick.title} (${pick.sec}s)` : 'NOT FOUND')
}

const keys = [...new Set([...Object.keys(result), ...used])].sort()
const body = keys.map((k) => `  ${k}: ${result[k] ? JSON.stringify(result[k]) : 'null'},`).join('\n')
writeFileSync('src/lib/videos.ts', `// Generated by scripts/find-videos.mjs (YouTube Data API) — one embeddable technique video per exercise.\nexport interface Video { id: string; title: string; channel: string; sec: number }\nexport const VIDEOS: Record<string, Video | null> = {\n${body}\n}\n`)
console.log('found', keys.filter((k) => result[k]).length, 'of', keys.length)
